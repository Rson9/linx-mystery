import { test, expect } from '@playwright/test';
test('桌宠从唤醒到录音、提示、文字作答、结算和下一题（模拟 Agent）', async ({ page }, info) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const compact = info.project.name === 'pet-compact';
  await page.goto(compact ? '/?compact=1' : '/');
  await expect(page.locator('#pet-device')).toHaveAttribute('data-mood', 'sleeping');
  await page.screenshot({ path: `test-results/${info.project.name}-welcome.png`, fullPage: true });
  await page.locator('#wake').click();
  await expect(page.locator('#connection')).toContainText('灵矽已连接');
  await expect(page.locator('#case-title')).toHaveText('没有响的门铃');
  await expect(page.locator('#speech-text')).toContainText('没有响的门铃');
  await page.locator('#mic').click();
  await expect(page.locator('#mic')).toHaveClass(/recording/, { timeout: 12000 });
  await page.waitForTimeout(500);
  await page.locator('#mic').click();
  await expect(page.locator('#mic')).not.toHaveClass(/recording/);
  await expect(page.locator('#questions')).toHaveText('1');
  await expect(page.locator('#clue-count')).toHaveText('1 条');
  await page.locator('#hint').click();
  await expect(page.locator('#hints')).toHaveText('1');
  if (compact) await page.locator('#show-board').click();
  await page.locator('#reveal').click();
  await expect(page.locator('#confirm-dialog')).toBeVisible();
  await page.locator('#cancel').click();
  await expect(page.locator('#case-status')).toHaveText('正在推理');
  await page.locator('#text').fill('房主穿蓝色衣服吗？'); await page.locator('#send').click();
  await expect(page.locator('#conversation')).toContainText('无法确定');
  await expect(page.locator('#questions')).toHaveText('1');
  await page.locator('#answer-mode').click();
  await page.locator('#text').fill('房主听不见，门铃通过室内灯闪提醒他开门');
  await page.locator('#send').click();
  await expect(page.locator('#result-title')).toHaveText('破案成功 · 85 分');
  await expect(page.locator('#case-status')).toHaveText('已破案');
  if (compact) await page.locator('#compact').click();
  await page.screenshot({ path: `test-results/${info.project.name}-won.png`, fullPage: true });
  await page.locator('#next').click();
  await expect(page.locator('#case-title')).toHaveText('雨天的十八楼');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.evaluate(() => { navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('test permission denied', 'NotAllowedError'); }; });
  await page.locator('#mic').click();
  await expect(page.locator('#notice')).toContainText('麦克风未获授权');
  await expect(page.locator('#text')).toBeVisible();
  await page.locator('#wake').click();
  await expect(page.locator('#connection')).toContainText('等待唤醒');
  expect(errors).toEqual([]);
});
