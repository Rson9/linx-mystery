import { test, expect } from '@playwright/test';
test('完整试玩、刷新恢复、确认揭晓和换关', async ({ page }, info) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: '开启第一道谜题' })).toBeVisible();
  await expect(page.locator('.case-card')).toHaveCount(5);
  await page.screenshot({ path: `test-results/${info.project.name}-welcome.png`, fullPage: true });
  await page.getByRole('button', { name: '开启第一道谜题' }).click();
  await expect(page.locator('#case-title')).toHaveText('没有响的门铃');
  await page.getByRole('button', { name: '和灯光有关吗？', exact: true }).click();
  await expect(page.locator('#history')).toContainText('闪光灯');
  await page.reload();
  await expect(page.locator('#questions')).toHaveText('1');
  await page.getByRole('button', { name: '✦ 给我提示', exact: true }).click();
  await expect(page.locator('#hints')).toHaveText('1');
  await page.getByRole('textbox').fill('我的答案是房主听不见，门铃通过闪光灯提醒他');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.locator('#game-status')).toHaveText('已破案');
  await expect(page.locator('#score')).toHaveText('85 分');
  await page.getByRole('button', { name: '下一道 →', exact: true }).click();
  await expect(page.locator('#case-title')).toHaveText('雨天的十八楼');
  await page.getByRole('button', { name: '揭晓真相', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: '继续推理', exact: true }).click();
  await expect(page.locator('#game-status')).toHaveText('推理中');
  await page.getByRole('button', { name: '揭晓真相', exact: true }).click();
  await page.getByRole('button', { name: '确认', exact: true }).click();
  await expect(page.locator('#game-status')).toHaveText('已揭晓');
  await expect(page.locator('#history')).toContainText('长柄雨伞');
  await page.screenshot({ path: `test-results/${info.project.name}-game.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
